-- Board 11869 part 6. His call, 23 Nov: do a NEW one - the clean floor gets its
-- own job and claim rather than the old build_record / job_order pair, which
-- carry ORDER-n string parsing and are not among the eight that must never be cut.
--
-- These two tables are the missing spine. The witness needs three things: the
-- plan the human wrote (plan_given, already here), the world (commit_seen and
-- commit_object, already here), and what the worker SAYS it did - which had no
-- home at all until now. job is the unit of work; claim is the worker's story
-- about it. Both append-only by intent.
--
-- Decisions declared:
--  (1) job.repo_link_id is NOT NULL. The old door had to parse 'ORDER-n' out of
--      a text field and, failing that, guess the repo when exactly one was
--      linked - refusing otherwise. A job that names its repo up front designs
--      that whole guess away. The 'not-checkable' verdict stays in the door for
--      its other causes (a local path, a path that is not repo-shaped).
--  (2) claim.job_id is NOT NULL, so every claim is anchored to a job and through
--      it to a repo. A claim floating free cannot be checked against anything.
--  (3) claim is one row per telling, never updated. A worker that re-claims
--      leaves both stories standing; which one matched is the evidence.
--  (4) files_claimed is text[], the same type the old door walked, and the
--      sentinel '{NONE}' keeps its meaning: nothing claimed, so nothing denied.
--  (5) plan_given.job_id is NOT given its foreign key here, on purpose. The
--      table still holds three leftover test rows ('first item' and friends)
--      whose job_id is 11685 - an old board number used as a stand-in, not a
--      job. Adding the key fails on them, and clearing customer-facing rows is
--      not a call to make unasked. Logged as the last loose end of this board.
--  (6) Paired account FKs as everywhere else on this floor, so a claim can
--      never reach another house's job or repo.

CREATE TABLE IF NOT EXISTS guardops.job (
    id           bigint      NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    account_id   bigint      NOT NULL DEFAULT guardops.current_account(),
    repo_link_id bigint      NOT NULL,
    what_for     text        NOT NULL,
    opened_at    timestamptz NOT NULL DEFAULT now(),
    closed_at    timestamptz,
    opened_by    text        NOT NULL DEFAULT SESSION_USER,
    CONSTRAINT job_pkey PRIMARY KEY (id),
    CONSTRAINT job_id_account_key UNIQUE (id, account_id),
    CONSTRAINT job_what_for_nonblank CHECK (length(btrim(what_for)) > 0),
    CONSTRAINT job_account_id_fkey FOREIGN KEY (account_id) REFERENCES guardops.account(id),
    CONSTRAINT job_repo_link_acct_fkey FOREIGN KEY (repo_link_id, account_id) REFERENCES guardops.repo_link(id, account_id)
);

COMMENT ON TABLE guardops.job IS
  'One unit of work handed to a worker, pinned to the repo it is allowed to touch. The plan rows in plan_given belong to a job; the worker story about it lands in claim. Append-only apart from closed_at.';

CREATE TABLE IF NOT EXISTS guardops.claim (
    id            bigint      NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    account_id    bigint      NOT NULL DEFAULT guardops.current_account(),
    job_id        bigint      NOT NULL,
    sha_claimed   text,
    files_claimed text[],
    claimed_at    timestamptz NOT NULL DEFAULT now(),
    claimed_by    text        NOT NULL DEFAULT SESSION_USER,
    CONSTRAINT claim_pkey PRIMARY KEY (id),
    CONSTRAINT claim_id_account_key UNIQUE (id, account_id),
    CONSTRAINT claim_account_id_fkey FOREIGN KEY (account_id) REFERENCES guardops.account(id),
    CONSTRAINT claim_job_acct_fkey FOREIGN KEY (job_id, account_id) REFERENCES guardops.job(id, account_id)
);

COMMENT ON TABLE guardops.claim IS
  'What the worker says it did on a job: the commit it claims and the files it claims to have touched. One row per telling, never updated - a re-claim leaves both stories standing. NULL or the NONE sentinel means nothing was claimed, which reads unproven rather than false.';

CREATE INDEX IF NOT EXISTS claim_by_job_idx ON guardops.claim (account_id, job_id, claimed_at DESC);
CREATE INDEX IF NOT EXISTS job_open_idx ON guardops.job (account_id, opened_at DESC) WHERE closed_at IS NULL;
