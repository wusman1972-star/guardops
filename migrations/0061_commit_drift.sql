-- Board 11869 part 4. RECONSTRUCTED, not lifted: guardops.commit_drift is gone
-- from BOTH floors and is nowhere in the repo. Its shape comes from the only
-- surviving statement of it - the two inserts inside commit_record, which name
-- (account_id, repo_link_id, sha, pull_id, kind, differed, resolved_at) for a
-- PATCH_FILLED and the same list without resolved_at for a CONTENT_DRIFT.
-- Decisions declared, not slipped in:
--  (1) id is an identity column. The inserts never supply an id, so the column
--      must default. BY DEFAULT rather than ALWAYS so a restore can carry ids.
--  (2) noticed_at defaults to now(). The inserts never name it, so the original
--      had a default; a drift record with no time is worth little.
--  (3) kind is CHECKed to the two values commit_record actually writes.
--  (4) resolved_at stays nullable: only a filled patch is resolved as it lands.
--      A CONTENT_DRIFT is the bell that has to stay ringing.
--  (5) account_id keeps the paired FKs the rest of this floor uses, so a drift
--      row can never point at another house's link or pull.
-- This table is append-only by intent: nothing in the product updates or
-- deletes a drift row, because the record of a rewrite is the evidence.

CREATE TABLE IF NOT EXISTS guardops.commit_drift (
    id           bigint      NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    account_id   bigint      NOT NULL DEFAULT guardops.current_account(),
    repo_link_id bigint      NOT NULL,
    sha          text        NOT NULL,
    pull_id      bigint      NOT NULL,
    kind         text        NOT NULL,
    differed     jsonb       NOT NULL,
    noticed_at   timestamptz NOT NULL DEFAULT now(),
    resolved_at  timestamptz,
    CONSTRAINT commit_drift_pkey PRIMARY KEY (id),
    CONSTRAINT commit_drift_kind_ck CHECK (kind IN ('PATCH_FILLED','CONTENT_DRIFT')),
    CONSTRAINT commit_drift_sha_nonblank CHECK (length(btrim(sha)) > 0),
    CONSTRAINT commit_drift_account_id_fkey FOREIGN KEY (account_id) REFERENCES guardops.account(id),
    CONSTRAINT commit_drift_repo_link_acct_fkey FOREIGN KEY (repo_link_id, account_id) REFERENCES guardops.repo_link(id, account_id),
    CONSTRAINT commit_drift_pull_acct_fkey FOREIGN KEY (pull_id, account_id) REFERENCES guardops.repo_pull(id, account_id)
);

CREATE INDEX IF NOT EXISTS commit_drift_unresolved_idx
    ON guardops.commit_drift (account_id, noticed_at DESC)
    WHERE resolved_at IS NULL;

COMMENT ON TABLE guardops.commit_drift IS
  'The record of a sha coming back with different content than was first seen. PATCH_FILLED is the one lawful difference (a placeholder filled by the real patch) and lands resolved. CONTENT_DRIFT is the bell: it lands unresolved and nothing in the product clears it. Append-only - field names only, never the patches.';
